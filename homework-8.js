/*
  Справка по методу .map():
  Метод .map() перебирает каждый элемент массива, применяет к нему колбэк-функцию
  и на основе возвращаемых значений формирует абсолютно НОВЫЙ массив такой же длины.
  Оригинальный массив при этом не изменяется.
*/

function markRareBooks(booksArray) {
  // Возвращаем новый массив, созданный методом .map()
  return booksArray.map(book => {
    // Используем поверхностное копирование через spread (...book), 
    // чтобы не изменять объекты в исходном массиве напрямую
    return {
      ...book,
      isRare: book.year > 2000 // true, если год больше 2000, иначе false
    };
  });
}

